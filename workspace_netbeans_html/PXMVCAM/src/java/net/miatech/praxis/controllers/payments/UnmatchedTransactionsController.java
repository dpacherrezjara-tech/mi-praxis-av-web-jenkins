    public List<A2290Filter> getList(HttpServletRequest request, Boolean bExcel) {

        List<A2290Filter> lst = new ArrayList<>(0);
        A2290Filter filter = new A2290Filter();
        Gson gson = new Gson();
        String beanString = "";
        Connection cnx = null;

        try {

            logic = new UnmatchedTransactionsLogic();
            logic.setSession(this.serverSession.getServerSession());

            beanString = request.getParameter("beanString");
            filter = gson.fromJson(beanString, A2290Filter.class);
            filter.page.TOTROW = -1;
            filter.page.START = 0;
            filter.page.LIMIT = 0;

            int limit = request.getParameter("limit") == null ? -1 : Integer.parseInt(request.getParameter("limit").toString());
            int start = request.getParameter("start") == null ? 0 : Integer.parseInt(request.getParameter("start").toString());

            if (!bExcel) {
                filter.page.PAGROW = 20;
                start = (start != 0 ? start : 0);
                filter.page.PAGNUM = (start / filter.page.PAGROW) + 1;
            } else {
                filter.page.PAGROW = -1;
                filter.page.PAGNUM = 1;
            }

            HashMap<String, String> hmDescError = new MasterDAO(this.serverSession.getServerSession()).loadErrorHash();
            HashMap<String, String> hmDescCard = new MasterDAO(this.serverSession.getServerSession()).loadCardHash();

            if (filter.IN_STVAL.trim().equals("D")) {
                lst = logic.loadPX297SQP00940(filter, hmDescError, hmDescCard);
            } else {
                lst = logic.loadPX297SQP00891(filter, hmDescError, hmDescCard);
            }

        } catch (Exception e) {
            throw new SpringException(e);
        }
        return lst;
    }

