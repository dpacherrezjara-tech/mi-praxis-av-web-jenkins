    public List<A1879Filter> getList(HttpServletRequest request, Boolean bExcel) {

        logic = new CommissionsGlLogic();

        List<A1879Filter> lst = new ArrayList<>(0);
        A1879Filter filter = new A1879Filter();

        filter.page.TOTROW = -1;
        filter.page.START = 0;
        filter.page.LIMIT = 0;

        try {

            logic.setSession(this.serverSession.getServerSession());

            filter.IN_A1879CCUST = request.getParameter("IN_A1879CCUST");
            filter.IN_A1879FECHA = request.getParameter("IN_A1879FECHA");
            filter.IN_A1879PERIO = request.getParameter("IN_A1879PERIO");

            System.out.println("----------------- Parametros --------------------- ");
            System.out.println(" limit : " + request.getParameter("limit"));
            System.out.println(" start : " + request.getParameter("start"));
            System.out.println("-------------------------------------------------- ");

            int limit = request.getParameter("limit") == null ? -1 : Integer.parseInt(request.getParameter("limit").toString());
            int start = request.getParameter("start") == null ? 0 : Integer.parseInt(request.getParameter("start").toString());

            if (!bExcel) {
                filter.page.PAGROW = 20;
                start = (start != 0 ? start : 0);
                filter.page.PAGNUM = (start / filter.page.PAGROW) + 1;
            } else {
                filter.page.PAGROW = -1;
                filter.page.PAGNUM = 1;
            }

            lst = logic.setPX153S01A1879(filter);

        } catch (Exception e) {
            throw new SpringException(e);
        }

        return lst;
    }

