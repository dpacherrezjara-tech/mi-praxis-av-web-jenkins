    @RequestMapping(value = "SearchBSPLINK")
    public @ResponseBody
    String SearchQueryRefund(ModelMap map, HttpServletRequest request) {
        List<A3093Filter> lst;
        A3093Filter filter = new A3093Filter();

        try {
            logic = new ControlBsplinkFormLogic();
            logic.setSession(this.serverSession.getServerSession());

            int limit = Integer.parseInt(request.getParameter("limit"));
            int start = Integer.parseInt(request.getParameter("start"));

            int pExcel = Integer.parseInt(request.getParameter("pexcel"));
            Boolean bExcel = pExcel == 1 ? true : false;

            filter.VP_OPTION = request.getParameter("VP_OPTION");
            filter.VP_COUNTRY = request.getParameter("VP_COUNTRY");
            filter.VP_DATE1 = request.getParameter("VP_DATE1");
            filter.VP_DETE2 = request.getParameter("VP_DETE2");
            filter.VP_FLAG = request.getParameter("VP_FLAG");

            if (!bExcel) {
                filter.page.PAGROW = 20;
                start = (start != 0 ? start : 0);
                filter.page.PAGNUM = (start / filter.page.PAGROW) + 1;
            } else {
                filter.page.PAGROW = -1;
                filter.page.PAGNUM = 1;
            }

            lst = logic.SearchReport(filter);
        } catch (Exception e) {
            throw new SpringException(e);
        }

        map.put("success", true);
        map.put("total", lst.size() > 0 ? lst.get(0).page.TOTROW : 0);
        map.put("data", lst);

        return new Gson().toJson(map);
    }

