    public List<A2865Filter> getList(HttpServletRequest request, Boolean bExcel) {

        logic = new LogCouponsUpdateLogic();

        List<A2865Filter> lst = new ArrayList<>(0);
        A2865Filter filter = new A2865Filter();

        filter.page.TOTROW = -1;
        filter.page.START = 0;
        filter.page.LIMIT = 0;

        try {

            logic.setSession(this.serverSession.getServerSession());

            filter.IN_A2865CCUST = request.getParameter("IN_A2865CCUST");
            filter.IN_FINI = request.getParameter("IN_FINI");
            filter.IN_FFIN = request.getParameter("IN_FFIN");

            int limit = request.getParameter("limit") == null ? -1 : Integer.parseInt(request.getParameter("limit").toString());
            int start = request.getParameter("start") == null ? 0 : Integer.parseInt(request.getParameter("start").toString());

            if (!bExcel) {
                filter.page.PAGROW = 20;
                start = (start != 0 ? start : 0);
                filter.page.PAGNUM = (start / filter.page.PAGROW) + 1;
            } else {
                filter.page.PAGROW = -1;
                filter.page.PAGNUM = 1;
            }

            lst = logic.SQP01298(filter);

        } catch (Exception e) {
            throw new SpringException(e);
        }

        return lst;
    }

